// Interface language. Strings are written in Simplified Chinese where they are used (app.js) and looked up here
// for the other languages. A value is a string with {placeholders}, or [one, many] for English counts on {n}.
const LANGS = { 'zh-Hans': '简体中文', 'zh-Hant': '繁體中文', en: 'English' };

// The server decides (the account's choice, or on pages before signing in, the one picked there or the browser's).
function detectLang() {
  const set = document.documentElement.dataset.lang;
  if (LANGS[set]) return set;
  for (const tag of navigator.languages || [navigator.language]) {
    let loc;
    try { loc = new Intl.Locale(tag).maximize(); } catch { continue; }
    if (loc.language === 'zh') return loc.script === 'Hant' ? 'zh-Hant' : 'zh-Hans';
    if (loc.language === 'en') return 'en';
  }
  return 'en';
}
